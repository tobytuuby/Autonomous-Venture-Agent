'use strict';
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const html = fs.readFileSync('ventures/venture-001/product/restock.html','utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, 'script exists');
const ctx = {module:{exports:{}}}; vm.createContext(ctx); vm.runInContext(script,ctx);
const {calculate, csv, importRows,HEADERS,SAMPLE} = ctx.module.exports;
const r = calculate(SAMPLE[0]); assert.equal(r.packs,3); assert.equal(r.quantity,37.5); assert.equal(r.cost,66);
assert.equal(calculate(SAMPLE[1]).packs,0);
assert.equal(calculate(SAMPLE[3]).packs,0);
assert.equal(calculate(['A','piece','S','L',11,0,10,20,5,3]).packs,0);
assert.equal(calculate(['A','piece','S','L',10,0,10,20,5,3]).packs,2);
assert.equal(calculate(['A','piece','S','L',1,9,10,20,6,3]).packs,2);
assert.throws(()=>calculate(['A','piece','S','L',-1,0,5,10,2,2]));
assert.throws(()=>calculate(['A','piece','S','L',1,0,5,3,2,2]));
assert.throws(()=>calculate(['A','piece','S','L',1,0,5,10,0,2]));
const cells = [[...HEADERS],...SAMPLE];
const restored = importRows(csv(cells));
assert.equal(JSON.stringify(restored),JSON.stringify(SAMPLE.map(row=>row.map(String))));
const guarded = csv([HEADERS,['=2+2','piece','Supplier','A',1,0,1,2,1,1]]);
assert.ok(guarded.includes("'=2+2"));
assert.equal(importRows(guarded)[0][0],'=2+2');
assert.throws(()=>importRows('bad,header\n'));
console.log('PASS: 13 worksheet checks');
